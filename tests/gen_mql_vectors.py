"""Generate MQL5/Scripts/OMNIX_OCL_TestVectors.mqh from tests/vectors.json.
Run after editing vectors:  python3 tests/gen_mql_vectors.py"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
V = json.loads((ROOT / "tests/vectors.json").read_text())
MQ = {"round_to_tick": "OCL_RoundToTick", "normalize_volume": "OCL_NormalizeVolume",
      "money_per_price_per_lot": "OCL_MoneyPerPricePerLot", "lots_for_risk": "OCL_LotsForRisk",
      "min_stop_distance": "OCL_MinStopDistance", "buy_stop_price": "OCL_BuyStopPrice",
      "sell_stop_price": "OCL_SellStopPrice", "trail_candidate": "OCL_TrailCandidate",
      "break_even_candidate": "OCL_BreakEvenCandidate", "cost_as_price": "OCL_CostAsPrice",
      "nth_weekday": "OCL_NthWeekdayOfMonth", "is_dst": "OCL_IsDST",
      "server_offset_seconds": "OCL_ServerOffsetSeconds", "minute_of_day": "OCL_MinuteOfDay",
      "in_window": "OCL_InWindow", "gold_name_score": "OCL_GoldNameScore"}
CAST = {"is_dst": "(datetime)", "server_offset_seconds": "(datetime)", "minute_of_day": "(datetime)"}


def lit(x):
    if isinstance(x, bool):
        return "true" if x else "false"
    if isinstance(x, str):
        return '"' + x + '"'
    if isinstance(x, float):
        return repr(x)
    return str(x)


lines = ["// AUTO-GENERATED by tests/gen_mql_vectors.py from tests/vectors.json - do not edit", "",
         "void OCL_RunVectorTests()", "  {"]
for name, rows in V.items():
    for i, row in enumerate(rows):
        *args, exp = row
        a = [lit(x) for x in args]
        if name in CAST:
            a[0] = CAST[name] + a[0]
        call = f"{MQ[name]}({','.join(a)})"
        label = f'"{name}#{i}"'
        if isinstance(exp, bool):
            lines.append(f"   CheckB({label},{call},{lit(exp)});")
        elif isinstance(exp, float):
            lines.append(f"   CheckD({label},{call},{lit(exp)});")
        else:
            lines.append(f"   CheckI({label},(long){call},{exp});")
lines += ["  }", ""]
(ROOT / "MQL5/Scripts/OMNIX_OCL_TestVectors.mqh").write_text("\n".join(lines))
print("wrote", sum(len(r) for r in V.values()), "checks")
